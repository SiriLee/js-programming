// Variable
let num = 30;
num = 50;
console.log(num);

// Const
const const_num = 100;
console.log(const_num);


// String
const str = "Hello, World!";
console.log(str);
console.log(typeof str);

// Number
const number = 42;
console.log(number);
console.log(typeof number);

// Boolean
const isTrue = true;
console.log(isTrue);
console.log(typeof isTrue);

// Null
const nullValue = null;
console.log(nullValue);
console.log(typeof nullValue); // Note: typeof null returns "object" due to a historical bug in JavaScript

// Undefined
let undefinedValue;
console.log(undefinedValue);
console.log(typeof undefinedValue);
